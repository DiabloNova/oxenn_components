import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = path.resolve(SCRIPT_DIR, "..");
const ALLOWED_METADATA_KEYS = new Set(["title", "icon", "order", "navigation"]);

function titleFromSlug(slug) {
  return slug
    .split(/[-_]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function readComponentMetadata(metadataPath, slug) {
  if (!existsSync(metadataPath)) {
    return { title: titleFromSlug(slug), icon: "Blocks", order: 1000, navigation: true };
  }

  let metadata;
  try {
    metadata = JSON.parse(readFileSync(metadataPath, "utf8"));
  } catch (error) {
    throw new Error(`Invalid JSON in ${metadataPath}: ${error.message}`);
  }

  if (!metadata || typeof metadata !== "object" || Array.isArray(metadata)) {
    throw new Error(`Component metadata in ${metadataPath} must be a JSON object.`);
  }

  const unsupportedKeys = Object.keys(metadata).filter((key) => !ALLOWED_METADATA_KEYS.has(key));
  if (unsupportedKeys.length > 0) {
    throw new Error(`Component metadata in ${metadataPath} contains unsupported field(s): ${unsupportedKeys.join(", ")}.`);
  }

  if (metadata.title !== undefined && (typeof metadata.title !== "string" || metadata.title.trim().length === 0)) {
    throw new Error(`The "title" field in ${metadataPath} must be a non-empty string.`);
  }
  if (metadata.icon !== undefined && (typeof metadata.icon !== "string" || metadata.icon.trim().length === 0)) {
    throw new Error(`The "icon" field in ${metadataPath} must be a non-empty string.`);
  }
  if (metadata.order !== undefined && (typeof metadata.order !== "number" || !Number.isFinite(metadata.order))) {
    throw new Error(`The "order" field in ${metadataPath} must be a finite number.`);
  }
  if (metadata.navigation !== undefined && typeof metadata.navigation !== "boolean") {
    throw new Error(`The "navigation" field in ${metadataPath} must be a boolean.`);
  }

  return {
    title: metadata.title?.trim() ?? titleFromSlug(slug),
    icon: metadata.icon?.trim() ?? "Blocks",
    order: metadata.order ?? 1000,
    navigation: metadata.navigation ?? true,
  };
}

export function discoverComponents(componentsDir) {
  if (!existsSync(componentsDir) || !statSync(componentsDir).isDirectory()) {
    throw new Error(`Component routes directory does not exist: ${componentsDir}`);
  }

  return readdirSync(componentsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .filter((entry) => {
      const pagePath = path.join(componentsDir, entry.name, "page.tsx");
      return existsSync(pagePath) && statSync(pagePath).isFile();
    })
    .map((entry) => {
      const slug = entry.name;
      const metadata = readComponentMetadata(path.join(componentsDir, slug, "component.json"), slug);
      return {
        slug,
        href: `/components/${slug}`,
        title: metadata.title,
        icon: metadata.icon,
        order: metadata.order,
        navigation: metadata.navigation,
      };
    })
    .sort((left, right) => left.order - right.order || (left.slug < right.slug ? -1 : left.slug > right.slug ? 1 : 0));
}

export function renderRegistry(entries) {
  return [
    "// This file is generated by `npm run generate:registry`. Do not edit manually.",
    `export const componentRegistry = ${JSON.stringify(entries, null, 2)} as const;`,
    "export type ComponentRegistryItem = (typeof componentRegistry)[number];",
    "",
  ].join("\n");
}

export function generateRegistry({ rootDir = REPOSITORY_ROOT, check = false } = {}) {
  const componentsDir = path.join(rootDir, "app", "components");
  const outputPath = path.join(rootDir, "generated", "component-registry.ts");
  const expected = renderRegistry(discoverComponents(componentsDir));

  if (check) {
    if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== expected) {
      throw new Error("The component registry is out of date. Run `npm run generate:registry` and commit the generated file.");
    }
    return false;
  }

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, expected, "utf8");
  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    const unsupportedArgs = args.filter((argument) => argument !== "--check");
    if (unsupportedArgs.length > 0 || args.filter((argument) => argument === "--check").length > 1) {
      throw new Error(`Unsupported arguments: ${unsupportedArgs.join(", ") || args.join(", ")}`);
    }
    const check = args.includes("--check");
    generateRegistry({ check });
    console.log(check ? "Component registry is up to date." : "Generated generated/component-registry.ts.");
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
